/*
 * tests/gvar-bearings/main.c
 *
 * Regression test for gvar phantom-point (side-bearing and advance)
 * deltas.  A variable TrueType glyph carries four extra 'phantom' points
 * beyond its outline; their deltas encode lsb/rsb/tsb/bsb and advance
 * variations.  This checks that FreeType:
 *
 *   - applies gvar phantom deltas to bearings and advances,
 *   - interpolates them at partial normalized coordinates,
 *   - keeps HVAR/VVAR authoritative for advances while gvar still drives
 *     the bearings,
 *   - honors both shared and embedded tuple encodings,
 *   - rejects malformed gvar data with FT_Err_Invalid_Table,
 *   - leaves a font without gvar unchanged at any coordinate.
 *
 * The fonts are generated by make-fonts.py using only the Python standard
 * library.  Geometry and expected numbers are documented there.
 *
 * Distributed under the FreeType project license, LICENSE.TXT.
 */
#include <stdio.h>
#include <string.h>

#include <ft2build.h>
#include FT_FREETYPE_H
#include FT_MULTIPLE_MASTERS_H
#include FT_OUTLINE_H


  /* A single expected metrics sample at one normalized coordinate. */
  typedef struct  Expect_
  {
    FT_Fixed  coord;        /* normalized blend coordinate        */
    FT_Pos    hori_bearing_x;
    FT_Pos    hori_advance;
    FT_Pos    vert_bearing_y;
    FT_Pos    vert_advance;

  } Expect;


  static FT_Library  library;


  static int
  check( const char*  what,
         FT_Pos       got,
         FT_Pos       want )
  {
    if ( got != want )
    {
      fprintf( stderr, "  FAIL %s: got %ld, want %ld\n",
               what, (long)got, (long)want );
      return 1;
    }
    return 0;
  }


  static const char*
  font_path( const char*  testdata_dir,
             const char*  name )
  {
    static char  path[FILENAME_MAX];


    snprintf( path, sizeof ( path ), "%s/%s", testdata_dir, name );
    return path;
  }


  /* Load one glyph at several coordinates and compare the full set of
     horizontal and vertical metrics.  Runs in FT_LOAD_NO_SCALE so the
     numbers are plain font units, independent of ppem. */
  static int
  run_metrics( const char*    filename,
               FT_UInt        glyph_index,
               const Expect*  expect,
               FT_UInt        count )
  {
    FT_Face  face;
    FT_UInt  i;
    int      failures = 0;


    if ( FT_New_Face( library, filename, 0, &face ) )
    {
      fprintf( stderr, "FAIL could not open %s\n", filename );
      return 1;
    }

    for ( i = 0; i < count; i++ )
    {
      FT_Fixed  coord = expect[i].coord;


      if ( FT_Set_Var_Blend_Coordinates( face, 1, &coord ) )
      {
        fprintf( stderr, "FAIL %s: could not set coordinate 0x%lx\n",
                 filename, (long)coord );
        failures = 1;
        continue;
      }

      if ( FT_Load_Glyph( face, glyph_index,
                          FT_LOAD_NO_SCALE | FT_LOAD_NO_HINTING |
                            FT_LOAD_VERTICAL_LAYOUT ) )
      {
        fprintf( stderr, "FAIL %s: could not load glyph %u at 0x%lx\n",
                 filename, glyph_index, (long)coord );
        failures = 1;
        continue;
      }

      failures |= check( "horiBearingX",
                         face->glyph->metrics.horiBearingX,
                         expect[i].hori_bearing_x );
      failures |= check( "horiAdvance",
                         face->glyph->metrics.horiAdvance,
                         expect[i].hori_advance );
      failures |= check( "vertBearingY",
                         face->glyph->metrics.vertBearingY,
                         expect[i].vert_bearing_y );
      failures |= check( "vertAdvance",
                         face->glyph->metrics.vertAdvance,
                         expect[i].vert_advance );
    }

    FT_Done_Face( face );
    if ( failures )
      fprintf( stderr, "FAIL metrics in %s\n", filename );
    return failures;
  }


  /* Glyph A: outline shifts by (20,4); phantoms pp1 +=40, pp2 +=60
     (advance +20), pp3 +=10, pp4 -=30 (vadvance +40).  Coordinates below
     are normalized [0,1], so the deltas scale linearly. */
  static int
  test_glyph_a( const char*  testdata_dir,
                const char*  name )
  {
    /*              coord   hbx   hadv   vby   vadv */
    Expect  e[4] = {
      { 0x00000,  100,  600,   300, 1000 },
      { 0x4000,    95,  605,   302, 1010 },  /* 0.25 of the deltas */
      { 0x8000,    90,  610,   303, 1020 },  /* 0.50 */
      { 0x10000,   80,  620,   306, 1040 }   /* 1.00 */
    };

    return run_metrics( font_path( testdata_dir, name ), 1, e, 4 );
  }


  /* Glyph V: static outline, only the vertical phantoms move (pp3 +=20,
     pp4 -=40).  The top bearing is derived from the static outline, so it
     stays fixed; the vertical advance grows by 60 at full strength.
     Horizontal metrics are untouched. */
  static int
  test_glyph_v( const char*  testdata_dir,
                const char*  name )
  {
    /*              coord  hbx  hadv   vby  vadv */
    Expect  e[4] = {
      { 0x00000,   50, 500,   550, 800 },
      { 0x4000,    50, 500,   555, 815 },
      { 0x8000,    50, 500,   560, 830 },
      { 0x10000,   50, 500,   570, 860 }
    };

    return run_metrics( font_path( testdata_dir, name ), 2, e, 4 );
  }

  /* With HVAR/VVAR present the advances come from those tables, not from
     gvar: horizontal advance gains 70 and vertical advance is pinned by
     VVAR (glyph A has a zero VVAR delta).  Bearings remain gvar-driven. */
  static int
  test_hvar_vvar_priority( const char*  testdata_dir )
  {
    /*              coord   hbx   hadv   vby   vadv */
    Expect  a[4] = {
      { 0x00000,  100,  600,   300, 1000 },
      { 0x4000,   105,  618,   299, 1000 },
      { 0x8000,   110,  635,   298, 1000 },
      { 0x10000,  120,  670,   296, 1000 }
    };
    /* Glyph V: VVAR delta +90 (rounded at each coordinate), HVAR delta 0,
       so horizontal metrics and the gvar-driven top bearing are fixed. */
    Expect  v[4] = {
      { 0x00000,   50, 500,   550, 800 },
      { 0x4000,    50, 500,   550, 823 },
      { 0x8000,    50, 500,   550, 845 },
      { 0x10000,   50, 500,   550, 890 }
    };
    int  failures = 0;


    failures |= run_metrics(
      font_path( testdata_dir, "gvar-hvar.ttf" ), 1, a, 4 );
    failures |= run_metrics(
      font_path( testdata_dir, "gvar-hvar.ttf" ), 2, v, 4 );
    return failures;
  }


  /* A font without gvar must ignore blend coordinates entirely and never
     raise an error. */
  static int
  test_no_gvar( const char*  testdata_dir )
  {
    static const Expect  e[2] = {
      { 0x00000, 100, 600, 300, 1000 },
      { 0x10000, 100, 600, 300, 1000 }
    };

    return run_metrics(
      font_path( testdata_dir, "gvar-nogvar.ttf" ), 1, e, 2 );
  }


  /* Every malformed fixture must open as a face but fail once a non-default
     coordinate selects the variation data.  Structural gvar faults (bad
     version, axis count, glyph count) are reported when the blend is set
     up; a corrupt per-glyph tuple is reported at glyph load.  Both stages
     must surface FT_Err_Invalid_Table rather than silent garbage or a
     crash. */
  static int
  test_malformed( const char*  testdata_dir )
  {
    static const char* const  names[] = {
      "gvar-bad-version.ttf",
      "gvar-bad-axis.ttf",
      "gvar-bad-count.ttf",
      "gvar-bad-tuplesize.ttf"
    };

    FT_Fixed  coord = 0x10000;
    FT_UInt   i;
    int       failures = 0;


    for ( i = 0; i < sizeof ( names ) / sizeof ( names[0] ); i++ )
    {
      FT_Face   face;
      FT_Error  error;


      if ( FT_New_Face( library,
                        font_path( testdata_dir, names[i] ), 0, &face ) )
      {
        fprintf( stderr, "FAIL %s: face should still open\n", names[i] );
        failures = 1;
        continue;
      }

      error = FT_Set_Var_Blend_Coordinates( face, 1, &coord );
      if ( !error )
        error = FT_Load_Glyph( face, 1,
                               FT_LOAD_NO_SCALE | FT_LOAD_NO_HINTING );

      if ( error != FT_Err_Invalid_Table )
      {
        fprintf( stderr,
                 "FAIL %s: expected Invalid_Table (0x%x), got 0x%lx\n",
                 names[i], FT_Err_Invalid_Table, (long)error );
        failures = 1;
      }

      FT_Done_Face( face );
    }

    return failures;
  }


  int
  main( int     argc,
        char**  argv )
  {
    const char*  testdata_dir = getenv( "FREETYPE_TESTS_DATA_DIR" );
    int          failures = 0;


    /* The generated fonts live in the build directory; meson passes it as
       the first argument.  Fall back to the source data dir for manual
       runs. */
    if ( argc > 1 )
      testdata_dir = argv[1];
    else if ( !testdata_dir )
      testdata_dir = "../tests/gvar-bearings/data";

    if ( FT_Init_FreeType( &library ) )
    {
      fprintf( stderr, "Could not initialize FreeType\n" );
      return 1;
    }

    /* Shared tuple + shared point numbers (the common encoding). */
    failures |= test_glyph_a( testdata_dir, "gvar-bearings.ttf" );
    failures |= test_glyph_v( testdata_dir, "gvar-bearings.ttf" );

    /* Embedded private peak tuple. */
    failures |= test_glyph_a( testdata_dir, "gvar-embedded.ttf" );
    failures |= test_glyph_v( testdata_dir, "gvar-embedded.ttf" );

    /* Private per-tuple point numbers. */
    failures |= test_glyph_a( testdata_dir, "gvar-privatepoints.ttf" );
    failures |= test_glyph_v( testdata_dir, "gvar-privatepoints.ttf" );

    failures |= test_hvar_vvar_priority( testdata_dir );
    failures |= test_no_gvar( testdata_dir );
    failures |= test_malformed( testdata_dir );

    FT_Done_FreeType( library );

    if ( failures )
    {
      fprintf( stderr, "gvar-bearings: FAILED\n" );
      return 1;
    }

    printf( "gvar-bearings: OK\n" );
    return 0;
  }


